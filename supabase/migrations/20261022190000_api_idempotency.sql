-- Supabase-managed migration for the optional authenticated ERP retry ledger.
-- Intentionally contains no business data or seeded user information.
BEGIN;

CREATE TABLE IF NOT EXISTS public.api_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    operation VARCHAR(120) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    request_digest VARCHAR(64) NOT NULL,
    response JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_api_idempotency_actor_operation_key
        UNIQUE (actor_id, operation, request_key)
);

ALTER TABLE public.api_idempotency_requests ENABLE ROW LEVEL SECURITY;

-- Never expose recorded API responses through client-side Supabase roles.
REVOKE ALL ON TABLE public.api_idempotency_requests FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.api_idempotency_requests_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
