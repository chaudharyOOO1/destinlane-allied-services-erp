create function public.protect_site_master_identity() returns trigger language plpgsql set search_path=pg_catalog,public as $$
begin
 if new.site_code is distinct from old.site_code or new.client_id is distinct from old.client_id then raise exception 'Saved site identity cannot be changed'; end if;
 return new;
end;
$$;
revoke all on function public.protect_site_master_identity() from public,anon,authenticated;
create trigger site_master_identity_immutable before update of site_code,client_id on public.sites for each row execute function public.protect_site_master_identity();
create function public.protect_contract_client() returns trigger language plpgsql set search_path=pg_catalog,public as $$
begin
 if new.client_id is distinct from old.client_id then raise exception 'Saved contract client cannot be changed'; end if;
 return new;
end;
$$;
revoke all on function public.protect_contract_client() from public,anon,authenticated;
create trigger contract_client_immutable before update of client_id on public.client_contracts for each row execute function public.protect_contract_client();
