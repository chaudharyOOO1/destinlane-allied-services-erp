create table public.site_code_counter (
 id integer primary key check(id=1),next_number integer not null check(next_number>=1),
 created_at timestamptz not null default now(),updated_at timestamptz not null default now()
);
insert into public.site_code_counter(id,next_number)
select 1,greatest(1,coalesce(max(substring(site_code from 10)::integer)+1,1)) from public.sites where site_code ~ '^SITE-DAS-[0-9]{4,}$';
