-- Deny browser access to every baseline table; the backend owns authorization.
do $$
declare table_name text;
begin
 foreach table_name in array array['employees','employee_intimations','employee_joining_drafts',
 'employee_bank_accounts','employee_approval_categories','employee_approval_requests','employee_documents',
 'attendance','salary_records','expenses','bookkeeping_ledger','gst_collection_ledger','gst_itc_ledger',
 'corporate_compliances','attendance_exceptions','risk_flags'] loop
  execute format('alter table public.%I enable row level security',table_name);
  execute format('revoke all on public.%I from public,anon,authenticated',table_name);
 end loop;
end; $$;
