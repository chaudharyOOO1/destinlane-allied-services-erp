create table public.employees (
 id uuid primary key default gen_random_uuid(), employee_code text not null unique,
 name text not null, phone text not null unique, dob date, gender text,
 designation text, branch text, site_id integer references public.sites(id),
 joining_date date, category text, aadhaar_no text, pan_no text,
 permanent_address text, present_address text, emergency_contact text,
 marital_status text, intimation_id text unique, status text not null default 'DRAFT',
 status_reason text, created_at timestamptz not null default now()
);
create sequence public.employee_initial_code_seq;
create function public.generate_employee_code() returns trigger language plpgsql
set search_path=public,pg_temp as $$
begin
 if new.employee_code is null then
  new.employee_code := 'E-DAS-' || lpad(nextval('public.employee_initial_code_seq')::text,4,'0');
 end if;
 return new;
end; $$;
create trigger employee_code_default before insert on public.employees
for each row execute function public.generate_employee_code();

create table public.employee_intimations (
 id uuid primary key default gen_random_uuid(), intimation_id text not null unique,
 name text not null, phone text not null, client_id integer references public.clients(id),
 created_by integer references public.users(id), status text not null default 'INTIMATED',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create sequence public.employee_intimation_code_seq;
create function public.generate_employee_intimation_id() returns trigger language plpgsql
set search_path=public,pg_temp as $$
declare code text;
begin
 if new.intimation_id is null then
  code := nextval('public.employee_intimation_code_seq')::text;
  new.intimation_id := 'INT-DAS-' || lpad(code,greatest(4,length(code)),'0');
 end if;
 return new;
end; $$;
create trigger employee_intimation_code_default before insert on public.employee_intimations
for each row execute function public.generate_employee_intimation_id();

